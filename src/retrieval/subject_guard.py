# -*- coding: utf-8 -*-
"""主体一致闸：问的是「图书馆」，就不许拿「学生公寓大门」的条款去回答（2026-10-18 新增）。

要治的病
--------
手册里没有「图书馆开放时间」，但《学生公寓管理办法》第十九条长这样：

    第十九条  学生公寓大门开放时间为每天 6:00 至 23:30……

这句话跟「图书馆几点开门」在**句式**上几乎一模一样。重排器给了 0.0349 分
（刚好越过 0.03 的拒答前置阈值），免费模型就把「图书馆」代进句式，答成
「图书馆 6:00–23:30」，还挂上 [E1] 引用 —— 引用本身是真的，只是**主体被换掉了**。
这类错答比拒答坏得多：学生看不出破绽，还会照着做。

实测同一病灶的三个问法（本地，重排分）：

    图书馆几点开门、几点关门     top1=0.0349  ← 全是《学生公寓》第十九条
    图书馆开放时间               top1=0.0529  ← 同上
    学校食堂几点开门             top1=0.0248  ← 同上

三条证据里，「图书馆 / 食堂」一个字都没出现。也就是说：**证据里根本没有这个主体**，
模型只能靠句式硬套。

为什么不能只靠「抬阈值」
------------------------
60 题实测：正常题最低 0.1118、真拒答题最高 0.1093，中间只有 0.0025 的空档。
抬阈值是靠"一刀切分数"去分辨两类题，而这三道错答的分数（0.0248~0.0529）
落在空档**下方**、和"该拒的题"混在一起 —— 单靠分数分不开它们和别的手册外问题，
只能拼命往低压，结果什么都拦不住。所以改成看「主体」这个更本质的信号。

判据（两道闸，必须同时成立才拦）
--------------------------------
1. **证据够弱**：全部证据的最高分 < `WEAK_TOP`（默认 0.08）。
   这道闸的意义是**数学上保证不误伤**：题目本身证据分 ≥0.08 时，本闸**根本不启动**。
   而 60 题里正常题最低是 0.1118 —— 全都在这条线之上，一道都不会被碰到。
2. **主体无支撑**：问句里提到的场所（图书馆/食堂/快递…），在证据里出现的最高分
   < 最高分 × `SUPPORT_RATIO`（默认 0.2）；或者干脆一次都没出现。

   为什么要比值而不是"出现过就算"：「图书馆开放时间」那条题的第 2 条证据
   （《外国留学生管理办法》第十八条）里**恰好有「图书馆」三个字**，但它是
   0.0026 分、讲的是留学生待遇 —— 只按"出现过"就放行，闸门等于没装。

两个条件都满足 → 判拒答（和"手册里没有"同一个结论），后面会自然接到官网兜底
（`agent_qa._web_lookup`）：手册没有的，去官网找；官网也没有，老实拒。

反例（必须放行，不然是新的误拒）
--------------------------------
    学生公寓大门几点关      top1 含「公寓」→ 主体有支撑 → 放行
    宿舍里能用电磁炉吗      top1 含「宿舍/公寓」→ 放行
    图书馆的书弄丢了怎么赔  top1 是《违纪处分》第二十三条（含「图书馆」）→ 放行
    在食堂勤工助学有工时限制吗  「勤工助学」条款分很高（>0.08）→ 闸门不启动 → 放行

词表纪律
--------
`GROUPS` 里每组都要在 `data/clauses.json` 里数过词频（2026-10-18 实测，974 条）：

    图书馆 3 · 餐厅 1 · 宿舍 31 · 公寓 111 · 医务室 5 · 校医 9 · 创业园 24
    食堂 0 · 饭堂 0 · 快递 0 · 超市 0 · 体育馆 0 · 教学楼 0 · 校门 0 · 班车 0

「0 次」不是问题 —— 手册本来就没有这些场所的规定，问到了就该拒（或去官网）。
但**别把「大门」写进「校门」组**：手册里唯一的「大门」就是学生公寓那道门，
写进去等于给错答开后门。

关掉它：环境变量 `SUBJECT_GUARD=off`（不用改代码、不用重新部署）。
"""
from __future__ import annotations

import os

# (主体名, (手册/口语里的写法…))
# 一组的几个写法视为同一个主体 —— 只要证据里出现任一写法，就算"提到了这个主体"。
GROUPS: tuple[tuple[str, tuple[str, ...]], ...] = (
    ("图书馆", ("图书馆", "馆藏图书")),
    ("食堂", ("食堂", "饭堂", "餐厅", "膳食", "餐饮")),
    ("快递", ("快递", "收发室", "信件收发", "邮政")),
    ("超市", ("超市", "便利店", "小卖部")),
    ("体育场馆", ("体育馆", "体育场", "运动场", "操场", "健身房")),
    ("教学楼", ("教学楼", "课室")),
    ("校门", ("校门",)),          # ⚠ 不许加「大门」，见文件头最后一段
    ("班车", ("班车", "校车")),
    ("停车场", ("停车场",)),
    ("医务室", ("医务室", "校医", "卫生所")),
    ("宿舍", ("宿舍", "学生公寓", "公寓")),
)

# 证据最高分达到这个值 → 闸门不启动（题目本身有像样的证据，交给模型与校验器）。
# 取值依据：60 题正常题最低 0.1118、真拒答题最高 0.1093；三道主体替换错答最高 0.0529。
# 0.08 在「错答」之上、「所有正常题」之下 —— 所以对 60 题零误伤是算出来的，不是估的。
WEAK_TOP = 0.08
# 主体词在证据里的最高分，要达到"最高分 × 这个比值"才算有支撑。
# 「图书馆开放时间」那道：0.0026 / 0.0529 = 0.049 → 无支撑（正确拦下）。
SUPPORT_RATIO = 0.2


def _off() -> bool:
    return (os.environ.get("SUBJECT_GUARD") or "").strip().lower() in (
        "off", "0", "false", "no")


def _subjects(question: str) -> list[tuple[str, tuple[str, ...]]]:
    """问句里提到的场所主体（可能有多个，比如「从图书馆到食堂」）。"""
    q = question or ""
    return [(name, words) for name, words in GROUPS
            if any(w in q for w in words)]


def check(question: str, evidences) -> dict | None:
    """主体不符就返回说明字典，否则 None（＝放行，什么都不用做）。

    返回：{"subject": 主体名, "words": 写法, "top": 最高分, "support": 主体词最高分,
           "weak_top": 阈值, "ratio": 比值, "reason": 给人看的一句话}
    """
    if _off() or not evidences:
        return None

    hits = _subjects(question)
    if not hits:
        return None                      # 没提具体场所 → 不管，交给原有链路

    top = max((e.score or 0.0) for e in evidences)
    if top <= 0 or top >= WEAK_TOP:
        return None                      # 闸一：证据够强 → 不启动（零误伤保证）

    for name, words in hits:
        support = 0.0
        for e in evidences:
            if any(w in (e.text or "") for w in words):
                support = max(support, e.score or 0.0)
        if support >= top * SUPPORT_RATIO:
            continue                     # 这个主体在证据里有支撑 → 放行
        ratio = support / top if top else 0.0
        return {
            "subject": name,
            "words": list(words),
            "top": round(top, 4),
            "support": round(support, 4),
            "weak_top": WEAK_TOP,
            "ratio": round(ratio, 3),
            "reason": (f"主体不符：问的是「{name}」，但证据里最高分那条"
                       f"（{top:.4f}）没有提到它"),
        }
    return None


def hint(hit: dict | None) -> str:
    """给页面「内部过程」用的一句话；没命中就返回空串。"""
    if not hit:
        return ""
    return (f"主体一致闸：提问主体「{hit['subject']}」在证据中只占 "
            f"{hit['support']:.4f} 分（最高分 {hit['top']:.4f}，"
            f"低于弱证据线 {hit['weak_top']}）→ 判为答非所问，不交给模型")
