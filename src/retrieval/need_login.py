# -*- coding: utf-8 -*-
"""「这个问题得登录才能查」的判定与话术（2026-10-17 新增）。

为什么需要它
------------
有一类问题，手册里本来就不该有，官网公开页也永远查不到 —— 因为它问的是
**学生自己的数据**：我这学期绩点多少、我的课表、我欠不欠学费。

这类问题如果照常走「手册检索 → 没找到 → 去官网搜」，会白等 8 秒，
再得到一句「本手册中没有对应内容」—— 学生不会因此更明白，反而觉得
这个助手"什么都不懂"。他要的其实是一句话：
「这个得你登录学校系统自己看」。

所以这里做**提前分流**：命中就根本不去检索、不去搜官网，直接给出
平台名字和入口链接。

怎么判（两个条件同时成立才算）
------------------------------
1. **问的是自己**：出现「我的 / 我 / 本人 / 自己 / 咱」这类自称；
2. **问的是个人数据**：命中 `LOGIN_TOPICS` 里的词。

只要有一个不成立就不算。这是**故意收紧**的 —— 因为误判的代价很大：
「奖学金评选条件」被误当成个人数据，学生会以为手册里没有，其实手册
第四章写得清清楚楚。

所以还有第三道闸：命中 `PUBLIC_WORDS`（条件/标准/规定/流程/怎么申请…）
一律判成公共问题，放回正常链路。宁可漏分流（多查一次、多等几秒），
也不许误分流（把手册能答的题挡掉）。

话术口径
--------
· 只说**实测确认过**的平台名。2026-10-17 探测结果：`i.szpu.edu.cn` 与
  `ehall.szpu.edu.cn` 打开都是「统一身份认证平台」；而 `jw.`、`ecard.`
  现在会跳到「安全提示」页 —— 所以这里**不指名** jw / ecard，免得指错路。
· 不暴露任何技术细节（不说"我查不到""数据库里没有"），只说该去哪儿。
"""
from __future__ import annotations

import re

# 自称 —— 没有这些词，就不当"个人信息"处理。
# 用正则而不是固定词串：「我借的书」「我下节课」这种才是学生真实说法，
# 只列「我的」会漏掉一半。`(?!们)` 是为了放过「我们学校食堂几点开门」——
# 那是问公共信息，不是问自己。
SELF_RE = re.compile(r"我的|我本|本人|自己|咱|我(?!们)")

# 公共规则词 —— 出现就说明问的是"规定"而不是"我的数字"，一律放回正常链路
PUBLIC_WORDS = (
    "条件", "标准", "规定", "要求", "办法", "政策", "流程", "程序",
    "怎么申请", "如何申请", "怎样申请", "能不能", "可以吗", "是否",
    "多少分算", "算不算", "算作", "认定", "评定办法", "管理办法", "细则",
)

# 个人数据主题：(关键词, 给人看的说法)
LOGIN_TOPICS = (
    (("绩点", "gpa", "学分绩"), "本学期的绩点"),
    (("成绩", "分数", "挂了几科", "及格没"), "你的课程成绩"),
    (("课表", "上课时间表", "下节课", "几点上课"), "你的课表"),
    (("选课", "退课", "抢课", "补选"), "选课结果"),
    (("考试安排", "考场", "座位号", "准考证"), "你的考试安排"),
    (("学费", "住宿费", "缴费", "欠费", "交钱"), "你的缴费情况"),
    (("录取", "通知书", "录取结果"), "你的录取结果"),
    (("学籍", "在校证明", "成绩单", "在读证明"), "你的学籍信息"),
    (("借阅", "借了几本", "还书", "超期"), "你的图书借阅记录"),
    (("校园卡", "一卡通", "饭卡", "余额", "充值"), "你的校园卡余额"),
    (("宿舍", "床位", "室友"), "你的住宿分配"),
    (("请假", "销假", "审批到哪", "审批进度"), "你的请假审批进度"),
    (("奖学金名单", "助学金名单", "公示名单", "评上了"), "你的奖助学金评定结果"),
    (("学分够不够", "还差多少学分", "毕业审核", "能不能毕业"), "你的学分与毕业审核情况"),
)

# 平台（2026-10-17 实测：打开标题都是「统一身份认证平台」）
PLATFORM_NAME = "学校统一身份认证平台（办事大厅）"
PLATFORM_URL = "https://i.szpu.edu.cn"


def check(question: str) -> dict | None:
    """命中「得登录才能查」就返回一份话术，否则返回 None。

    返回：{"topic": 主题说法, "text": 直接给学生的答复, "url": 入口}
    """
    q = (question or "").strip()
    if not q:
        return None

    low = q.lower()

    # 闸一：得是问自己
    if not SELF_RE.search(q):
        return None

    # 闸二：得问的是"规定"以外的东西
    if any(w in low for w in PUBLIC_WORDS):
        return None

    # 闸三：得命中个人数据主题
    for keys, topic in LOGIN_TOPICS:
        if any(k in low for k in keys):
            return {
                "topic": topic,
                "url": PLATFORM_URL,
                "text": (
                    f"「{topic}」属于个人数据，需要登录{PLATFORM_NAME}才能查看。\n\n"
                    f"入口：{PLATFORM_URL}\n\n"
                    f"这类信息和每个人的账号绑定，学生手册和公开网页里不会有。"
                ),
            }
    return None


# ------------------------------------------------------------------ 自测
if __name__ == "__main__":
    import sys
    sys.stdout.reconfigure(encoding="utf-8")

    cases = [
        # 该命中
        ("我这学期绩点多少？", True),
        ("我的课表在哪看？", True),
        ("我欠不欠学费？", True),
        ("我借的书超期了吗", True),
        ("我的录取结果出来了吗", True),
        ("我下节课几点上课", True),
        # 不该命中（公共规则 / 问的不是自己 / 手册能答）
        ("奖学金评选条件是什么？", False),
        ("国家助学金的申请条件", False),
        ("我能不能申请奖学金？", False),
        ("校园卡丢了怎么办？", False),
        ("旷课太多会有什么后果？", False),
        ("学校的作息时间是怎样的？", False),
        ("我的专业能专升本吗", False),
    ]
    bad = 0
    for q, want in cases:
        got = check(q) is not None
        ok = got == want
        bad += 0 if ok else 1
        print(f"{'✓' if ok else '✗'} {'命中' if got else '不命中':4} | {q}")
        if got and not want:
            print("      ↳ 误判成个人数据，会把手册能答的题挡掉")
    print(f"\n{len(cases) - bad}/{len(cases)} 通过")
    sys.exit(1 if bad else 0)
