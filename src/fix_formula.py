# -*- coding: utf-8 -*-
"""公式重建补丁：修复 PDF 文本层把分式拍平后产生的乱序文本。

原理
----
PDF 里的分式不是"一行文字"，而是多个文本片段按坐标摆放：分子在上、分母在下、
横线与 Σ 是独立的符号字体字符。文本层按内部顺序输出，于是读出来变成
「课程学分绩点课程学分课程绩点平均课程绩点= =课程学分课程学分」这种乱序串。

做法
----
不做通用算法（风险高、易误伤），而是**按坐标人工核实后登记成补丁表**：
每条补丁记录 来源条款 / 匹配模式 / 重建文本 / 重建依据。
换新版本手册时只需更新补丁表，不动代码。

已核实的补丁（坐标见 src/rebuild 日志，2026-10-10）
----------------------------------------------------
[1] F08-A002 平均课程绩点公式（p71）
    PDF 原貌：两个分式并排，Symbol 字体 span 在各自分子左侧（Σ），
    分子『课程学分绩点』y≈308.5 / 分母『课程学分』y≈321.0（第一式）；
    分子『课程学分×课程绩点』y≈310.0 / 分母『课程学分』y≈322.1（第二式）。
    重建：平均课程绩点 = ∑课程学分绩点 ÷ ∑课程学分 = ∑(课程学分×课程绩点) ÷ ∑课程学分

[2] F08-A002 课程绩点计算公式（p70）
    PDF 原貌：『kr』x≈75.4,y≈390.9（斜体）→『=1+(X-60)×』y≈398.9；
    分子『3』x≈156.3,y≈391.6、分母『40』x≈154.0,y≈404.7，构成分式 3/40。
    重建：kr = 1 + (X-60) × 3/40（60≤X≤100）
    交叉校验：X=100 → 1+40×(3/40)=4.0；X=60 → 1.0
             与正文「100分对应绩点4.0、60分对应1.0」一致。
"""
import re

PATCHES = [
    {
        "clause_id": "F08-A002",
        "name": "课程绩点计算公式（p70）",
        "pattern": r"kr\s*=\s*1\s*\+\s*\(X\s*-\s*60\)\s*×\s*[（(]?\s*60\s*[≤<]\s*X\s*[≤<]\s*100\s*[)）]?",
        "rebuilt": "kr = 1 + (X - 60) × 3/40（60 ≤ X ≤ 100）",
    },
    {
        "clause_id": "F08-A002",
        "name": "平均课程绩点公式（p71）",
        # 注意：规范化会给「（二）」后补一个空格，此处必须容忍空白
        "pattern": r"（二）\s*平均课程绩点.{0,240}?(?=平均课程绩点在\s*1\.00)",
        "rebuilt": ("（二）平均课程绩点\n"
                    "平均课程绩点 = ∑课程学分绩点 ÷ ∑课程学分 "
                    "= ∑(课程学分 × 课程绩点) ÷ ∑课程学分\n"),
    },
]


def apply_patches(clause_id, text):
    """对单条条款文本应用补丁，返回 (新文本, 命中记录列表)。"""
    hits = []
    for p in PATCHES:
        if p["clause_id"] != clause_id:
            continue
        new, n = re.subn(p["pattern"], p["rebuilt"], text, count=1)
        if n:
            hits.append(p["name"])
            text = new
    return text, hits


if __name__ == "__main__":
    demo = ("考试课程综合成绩为100分的对应课程绩点为4.0，60分的对应课程绩点为1.0,"
            "60分以下课程绩点为0。60分～100分间对应的绩点计算公式如下："
            "kr=1+(X-60)×   （60≤X≤100）课程绩点带一位小数位（4舍5入）。"
            "表一：百分制、五级制、课程绩点的对应关系（二）平均课程绩点××"
            "课程学分绩点课程学分课程绩点平均课程绩点=             =课程学分课程学分"
            "平均课程绩点在1.00～4.00之间，采用带两位小数位形式（4舍5入）。")
    out, hits = apply_patches("F08-A002", demo)
    print("命中补丁:", hits)
    print()
    for sent in out.split("。"):
        if sent.strip():
            print(" ", sent.strip()[:110])
