def main():
    cl = {c["clause_id"]: c for c in
          json.load((ROOT / "data" / "clauses.json").open(encoding="utf-8"))}
    out = []
    missing = []
    for it in ITEMS:
        srcs = []
        for cid in it["clause_ids"]:
            c = cl.get(cid)
            if not c:
                missing.append((it["qid"], cid))
                continue
            ps, pe = c.get("page_start"), c.get("page_end")
            page = str(ps) if (pe in (None, ps)) else f"{ps}-{pe}"
            srcs.append({
                "clause_id": cid,
                "file_id": c["file_id"],
                "file_title": c["file_title"],
                "article_no": c.get("article_no"),
                "page": page,
            })
        out.append({
            "qid": it["qid"],
            "type": "cross",
            "question": it["question"],
            "answer": it["answer"],
            "must_contain": it["must_contain"],
            "sources": srcs,
            "note": it["note"],
        })
    if missing:
        print("!! 以下条款在 clauses.json 中不存在，请核对：")
        for q, cid in missing:
            print(f"   {q} -> {cid}")
    dst = ROOT / "data" / "new_items_draft.json"
    dst.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"已写出 {dst}，共 {len(out)} 题，sources 合计 "
          f"{sum(len(x['sources']) for x in out)} 条")
    for x in out:
        files = sorted({s['file_id'] for s in x['sources']})
        print(f"  {x['qid']}  文件数={len(files)} {files}  要点={len(x['must_contain'])}")


if __name__ == "__main__":
    main()
