# -*- coding: utf-8 -*-
"""口语词 → 手册用词 的对照表（2026-10-16 新增）。

为什么需要它
------------
学生用嘴说话，手册用笔写字。这两套词**字面上一个字都不重合**，
检索就抓瞎 —— 实测（真实词频，手册全文 974 条）：

    学生这么说        手册里出现   手册实际写
    体测              0 次        体质测试
    挂科              0 次        不及格、重修
    翘课              0 次        旷课
    打小抄            0 次        考试作弊
    蹲级              0 次        留级、降级
    打工              0 次        勤工助学
    操行分/德育分      0 次        综合素质评价
    转本              0 次        专升本

BM25 是按字面匹配的，一个字对不上就是零命中；向量虽然能兜一点，
但拉不开分。结果就是「体测成绩对奖学金是不是硬性要求」这种问题，
最高相关分只有 0.05，被最后那道「答案有没有原文撑腰」的校验判成
「证据只是擦边」→ 整题拒答。

换成手册的写法再问同一件事，分数立刻从 0.05 跳到 0.44，题就答出来了。

怎么用
------
`variants(question)` 产出若干条「换过词的同义问句」，交给
`agent_qa._ask()` 当作**额外的检索路**（本链路本来就支持一路或多路，
见 `_merge`）。多路结果按条款取最高分合并，所以多给几路**只会多找到
东西、不会把原来找到的弄丢**。

`hint_for(question)` 给「真查不到」时用：告诉学生手册里的写法是什么，
让他换个说法再问一次 —— 比干巴巴一句「本手册中没有对应内容」有用得多。

手工维护
--------
这张表是**人工核对过**的：左边每个词都在手册全文里数过，确认几乎不出现
（0~1 次），右边都是手册里真实存在的写法。**新增词条必须先在
`data/clauses.json` 里数一遍**，别凭印象加 —— 左边要是不为 0，说明学生
本来就是照手册说的，加了反而会干扰。
"""
from __future__ import annotations

# (学生口语, (手册写法…))
# 手册写法给多个时按「最常用」排前；全都会用上（见 variants）。
ALIASES: tuple[tuple[str, tuple[str, ...]], ...] = (
    # ---- 学籍 / 成绩 ----
    ("体测", ("体质测试",)),
    ("体质健康测试", ("体质测试",)),
    ("挂科", ("不及格", "重修")),
    ("挂了两科", ("不及格", "重修")),
    ("没过", ("不及格",)),
    ("重考", ("补考",)),
    ("补学分", ("重修",)),
    ("刷分", ("重修",)),
    ("蹲级", ("留级", "降级")),
    ("转本", ("专升本",)),
    ("大一", ("一年级",)),
    ("大二", ("二年级",)),
    ("大三", ("三年级",)),
    ("大四", ("四年级",)),
    # ---- 考勤 / 违纪 ----
    ("翘课", ("旷课",)),
    ("逃课", ("旷课",)),
    ("打小抄", ("考试作弊",)),
    ("抄答案", ("考试作弊",)),
    ("替考", ("考试作弊",)),
    ("代考", ("考试作弊",)),
    ("赶出去", ("开除学籍",)),
    ("劝退", ("退学",)),
    # ---- 评奖 / 资助 ----
    ("评奖学金", ("奖学金评选",)),
    ("操行分", ("综合素质评价",)),
    ("德育分", ("综合素质评价",)),
    ("综测", ("综合素质评价",)),
    ("打工", ("勤工助学",)),
    ("贫困生", ("家庭经济困难",)),
)

# 已经写对了的词 —— 别名**不许**在这些词的范围里生效。
#
# 起因（2026-10-16 表写好之后当场测出来的）：
#   表里原本有「拿奖 → 获奖」，于是学生问「还能**拿奖学金**吗」时，
#   "拿奖" 被当成命中 → 替换后整句变成「还能**获奖学金**吗」，把好端端的
#   「奖学金」写坏了。同一个坑还有「升本 → 专升本」：问「想专升本」会被
#   替成「想专专升本」。
#
# 那两条词条已直接删掉（词表宁缺毋滥）；下面这层是**兜底**：只要口语词的
# 命中区间跟这些正确写法有任何重叠，就判为「学生本来就是照手册说的」，
# 不算命中、也不做替换。以后往表里加词也不容易再踩同一个坑。
PROTECTED: tuple[str, ...] = (
    "奖学金", "助学金", "励志奖学金",
    "专升本", "综合素质评价",
)


def _find_all(text: str, needle: str):
    """找出 needle 在 text 里的全部出现区间 [start, end)。"""
    i = text.find(needle)
    while i >= 0:
        yield i, i + len(needle)
        i = text.find(needle, i + 1)


def _overlaps_protected(text: str, start: int, end: int) -> bool:
    for p in PROTECTED:
        for ps, pe in _find_all(text, p):
            if start < pe and ps < end:            # 有重叠（含部分重叠）
                return True
    return False


def hits(question: str) -> list[tuple[str, tuple[str, ...]]]:
    """找出问句里命中的口语词，返回 [(口语词, 手册写法…)]（按出现先后）。

    没有命中就返回空列表 —— 调用方据此判断「要不要多走几路检索」。
    落在 PROTECTED 里的命中会被忽略（见上面的说明）。
    """
    q = question or ""
    out = []
    for spoken, manual in ALIASES:
        for s, e in _find_all(q, spoken):
            if _overlaps_protected(q, s, e):
                continue
            out.append((spoken, manual))
            break                                   # 同一个词只记一次
    return out


def variants(question: str) -> list[str]:
    """产出「换过词的同义问句」，供多路检索。

    一次性给三种机械写法（都是同一句话，不用猜任何关键词）：

      ① 追加：原句 + 手册词        —— 给 BM25 加命中词
      ② 前缀：手册词 + 原句        —— 让手册词在开头，向量更吃得住
      ③ 替换：把手口语词就地换成手册词

    为什么给三种而不是挑一种：实测它们各有所长，且**没有一种稳赢**。
    例（最高相关分）：
        体测…         追加 0.26 ＞ 前缀 0.19 ＞ 替换 0.12 ＞ 原句 0.05
        挂科…奖学金     替换 0.62 ＞ 前缀 0.58 ＞ 追加 0.38 ＞ 原句 0.22
        翘课多少节       替换 0.96 ＞ 前缀 0.91 ＞ 追加 0.85 ＞ 原句 0.74
    多路的代价只是几百毫秒（检索是并发的），而合并时**按条款取最高分**，
    所以三种都给，等于「哪个管用就用哪个」，稳。

    问句里没有口语词时返回空列表 —— 这种情况完全按原样走，不多花时间。
    """
    hs = hits(question)
    if not hs:
        return []

    q = (question or "").strip()
    all_terms = []
    for _, manual in hs:
        for t in manual:
            if t not in all_terms:
                all_terms.append(t)
    terms_str = " ".join(all_terms)

    replaced = q
    for spoken, manual in sorted(hs, key=lambda x: -len(x[0])):
        replaced = replaced.replace(spoken, manual[0])

    out = [f"{q} {terms_str}", f"{terms_str} {q}", replaced]
    # 去重、去掉跟原句一样的、保持顺序
    seen, uniq = set(), []
    for v in out:
        v = " ".join(v.split())
        if v and v != " ".join(q.split()) and v not in seen:
            seen.add(v)
            uniq.append(v)
    return uniq


def hint_for(question: str) -> str:
    """真查不到时，给学生一句「换个说法试试」的提示；没命中就返回空串。

    例（问句含「体测」）：
        手册里写的是「体质测试」，用这个说法再问一次可能就找得到。
    """
    hs = hits(question)
    if not hs:
        return ""
    parts = []
    for spoken, manual in hs[:2]:                  # 最多提示两个，别刷屏
        parts.append(f"「{spoken}」→「{'/'.join(manual)}」")
    return ("手册里的写法和日常说法不太一样："
            + "、".join(parts)
            + "。换成手册的说法再问一次，通常就能找到了。")
